// Builds wrangler.local.toml from the public template (wrangler.toml) and the three values
// only the maintainer has, kept in a settings file outside the repository. Every npm script
// that talks to Cloudflare runs this first, so the deployed config is always the current
// template plus those values, and a change to the template can't be missed.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

/// Outside the repository, so every checkout and worktree uses the same file and it can't be
/// committed. MACRAZER_REPORTS_SETTINGS points somewhere else.
export function settingsPath(env = process.env) {
  return env.MACRAZER_REPORTS_SETTINGS ?? join(homedir(), ".config", "macrazer-reports", "settings.env");
}

/// `KEY=value` lines. Blank lines and `#` comments are skipped; quotes around a value go.
export function parseSettings(text) {
  const settings = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 1) throw new Error(`Not a KEY=value line: ${line}`);
    settings[line.slice(0, eq).trim()] = line.slice(eq + 1).trim().replace(/^"(.*)"$/, "$1");
  }
  return settings;
}

const EMAIL = /^[^@\s"]+@[^@\s".]+(\.[^@\s".]+)+$/;
const DATABASE_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/// Each private value: where it goes in the template, and what it must look like.
const FIELDS = [
  { key: "DESTINATION", lines: ["destination_address", "DESTINATION_ADDRESS"], format: EMAIL },
  { key: "SENDER", lines: ["SENDER_ADDRESS"], format: EMAIL },
  { key: "DATABASE_ID", lines: ["database_id"], format: DATABASE_ID },
];

export function render(template, settings, source = settingsPath()) {
  const unknown = Object.keys(settings).filter((k) => !FIELDS.some((f) => f.key === k));
  if (unknown.length) throw new Error(`Unknown setting ${unknown.join(", ")} in ${source}`);
  let out = template;
  for (const { key, lines, format } of FIELDS) {
    const value = settings[key];
    if (!value) throw new Error(`${key} is missing from ${source}`);
    if (!format.test(value)) throw new Error(`${key} in ${source} doesn't look right: ${value}`);
    for (const name of lines) {
      const line = new RegExp(`^${name} = ".*"$`, "m");
      if (!line.test(out)) throw new Error(`wrangler.toml has no \`${name} = "..."\` line any more; update scripts/local-config.mjs`);
      out = out.replace(line, `${name} = "${value}"`);
    }
  }
  const header = [
    `# Generated by \`npm run config\` from wrangler.toml and ${source}.`,
    "# Don't edit it: changes for everyone go in wrangler.toml, your own values in that file.",
    "",
  ].join("\n");
  return header + out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = settingsPath();
  if (!existsSync(source)) {
    console.error(`No settings file at ${source}. See "Setup" in worker/README.md.`);
    process.exit(1);
  }
  const here = (name) => new URL(`../${name}`, import.meta.url);
  try {
    const out = render(readFileSync(here("wrangler.toml"), "utf8"), parseSettings(readFileSync(source, "utf8")), source);
    writeFileSync(here("wrangler.local.toml"), out);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
